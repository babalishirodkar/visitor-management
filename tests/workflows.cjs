const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('../.tools/node_modules/playwright-core');
const { default: AxeBuilder } = require('../.tools/node_modules/@axe-core/playwright');
const base = process.env.TEST_URL || 'http://localhost/visitor-management/';
const executablePath = process.env.CHROME_PATH || path.join(process.env.LOCALAPPDATA, 'ms-playwright/chromium-1223/chrome-win64/chrome.exe');
const checks = [], errors = [];
const check = (condition, message) => { assert.ok(condition, message); checks.push(message); console.log('PASS ' + message); };
const moduleUrl = (module, action = 'list', query = '') => `${base}pages/${module}/${module}-${action}.php${query}`;
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    const visit = async (module, action = 'list', query = '') => { await page.goto(moduleUrl(module, action, query)); };
    const axe = async label => {
      await page.evaluate(() => document.fonts.ready);
      // Finish finite entrance motion before measuring text contrast.
      await page.waitForTimeout(450);
      const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
      assert.deepEqual(result.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })), [], label);
      checks.push(label);
    };
    await visit('dashboard');
    check(page.url().endsWith('login.php'), 'Unauthenticated routes redirect to sign-in');
    const anonymousWrite = await context.request.post(moduleUrl('appointments', 'add'), { form: { visitor: 'Denied test' }, maxRedirects: 0 });
    check(anonymousWrite.status() === 302 && anonymousWrite.headers().location.endsWith('login.php'), 'Unauthenticated appointment submissions are rejected before a write');
    await page.locator('#togglePasswordBtn').click();
    check(await page.locator('#password').getAttribute('type') === 'text', 'Password visibility toggle works');
    await page.locator('#togglePasswordBtn').click();
    await page.locator('#email').fill('');
    await page.getByRole('button', { name: 'Sign in to Portal' }).click();
    check(await page.locator('.form-feedback').isVisible(), 'Sign-in gives inline required-field feedback');
    check(await page.locator('#email').evaluate(el => el === document.activeElement), 'Invalid field receives keyboard focus');
    await page.locator('#email').fill('vedkarmalkar@gmail.com');
    await page.locator('#password').fill('wrong-password');
    await page.getByRole('button', { name: 'Sign in to Portal' }).click();
    await page.waitForLoadState();
    check(await page.getByText('Invalid email or password.', { exact: false }).isVisible(), 'Invalid credentials retain server error feedback');
    await page.locator('#password').fill('Admin@123');
    await page.getByRole('button', { name: 'Sign in to Portal' }).click();
    await page.waitForURL('**/appointments-list.php');

    await page.locator('#filterStatus').selectOption('Approved');
    await page.locator('#filterSite').selectOption('Pune Plant');
    await page.locator('#tableQuickSearch').fill('Rohan');
    await page.waitForFunction(() => document.querySelector('#appointmentsTable-count').textContent.startsWith('1 of'));
    check(await page.locator('#appointmentsTable tbody tr:not([hidden]):not(.filter-empty)').count() === 1, 'Search, status and site filters compose');
    await page.locator('#tableQuickSearch').fill('Meera');
    await page.waitForFunction(() => !document.querySelector('.filter-empty').hidden);
    check(await page.locator('.filter-empty').isVisible(), 'No-match state appears without losing the table');
    await page.locator('.filter-empty button').click();
    check(await page.locator('#appointmentsTable tbody tr:not([hidden]):not(.filter-empty)').count() === 7, 'Clear filters restores all existing rows');
    check((await page.locator('script[src]').evaluateAll(s => s.map(x => x.src))).every(src => !src.includes('qrcode') && !src.includes('chart.umd')), 'Appointment list skips QR and chart payloads');

    await page.keyboard.press('Control+k');
    await page.locator('#workspaceQuery').waitFor({ state: 'visible' });
    await page.locator('#workspaceQuery').fill('material out');
    check(await page.locator('.workspace-result:not([hidden])').count() === 1, 'Workspace search matches multiple terms');
    await axe('Workspace search passes automated accessibility checks');
    await page.locator('#workspaceQuery').press('ArrowDown');
    await page.keyboard.press('Enter');
    await page.waitForURL('**/material-outward-list.php');
    await page.locator('select[data-filter-table="outTable"]').selectOption({ label: 'Returnable' });
    await page.waitForTimeout(50);
    check((await page.locator('#outTable tbody tr:not([hidden]):not(.filter-empty) td:nth-child(5)').allTextContents()).every(s => s === 'Returnable'), 'Returnable filter excludes Non-returnable');
    await page.getByRole('button', { name: 'New outward pass' }).click();
    await page.locator('#outModal').waitFor({ state: 'visible' });
    await page.locator('#outModal [type="submit"]').click();
    check(await page.locator('#outModal .form-feedback').isVisible(), 'Modal form validation stays in the dialog');
    await page.locator('#kindSel').selectOption('Non-returnable');
    check(await page.locator('#dueInp').evaluate(el => !el.required && el.closest('[hidden]') !== null), 'Outward kind toggles conditional required fields');
    await page.locator('[data-add-item="outItems"]').click();
    check(await page.locator('#outItems tbody tr').count() === 2, 'Material item rows can be added');
    check(await page.locator('#outItems tbody tr:last-child input').first().evaluate(el => el === document.activeElement), 'New material item receives focus');
    const ids = await page.locator('#outItems [id]').evaluateAll(nodes => nodes.map(n => n.id));
    check(ids.length === new Set(ids).size, 'Cloned rows do not duplicate field IDs');
    await page.locator('#outItems tbody tr:last-child [data-remove-item]').click();
    check(await page.locator('#outItems tbody tr').count() === 1, 'Material item rows can be removed');
    await page.locator('#outModal input[type="file"]').setInputFiles({ name: 'sample.txt', mimeType: 'text/plain', buffer: Buffer.from('Test attachment') });
    check(await page.locator('#outModal input[type="file"]').evaluate(el => el.files[0].name) === 'sample.txt', 'Existing upload controls accept a file');
    await axe('Material dialog passes automated accessibility checks');
    await page.locator('#outModal .btn-close').click();

    await visit('visitors');
    await page.locator('select[data-filter-table="visTable"]').selectOption('Supplier');
    await page.waitForTimeout(50);
    check((await page.locator('#visTable tbody tr:not([hidden]):not(.filter-empty) td:nth-child(4)').allTextContents()).every(s => s.trim() === 'Supplier'), 'Visitor categories filter the correct column');
    await page.getByRole('tab', { name: 'Categories', exact: false }).click();
    check(await page.locator('#tCats').isVisible(), 'Existing tabs remain functional');

    await visit('appointments', 'add');
    await page.getByRole('button', { name: 'Create Appointment', exact: false }).click();
    check(await page.locator('.form-feedback').isVisible(), 'Appointment required fields block submission');
    await page.locator('[name="visitor"]').fill("UI Review O'Connor");
    await page.locator('[name="company"]').fill('Design QA');
    await page.locator('[name="purpose"]').fill('Interface verification');
    await page.getByRole('button', { name: 'Create Appointment', exact: false }).click();
    await page.waitForURL('**/appointments-add.php?**created=1');
    const appointmentUrl = new URL(page.url());
    const id = appointmentUrl.searchParams.get('id');
    check(Boolean(id), 'Appointment creation persists in the existing session');
    check(await page.locator('#badgeQrBox svg').count() === 1, 'Appointment QR renders safely with apostrophes in names');
    await axe('Appointment detail passes automated accessibility checks');
    await visit('appointments', 'add', `?id=${id}&mode=edit`);
    await page.locator('[name="company"]').fill('Design QA Updated');
    await page.locator('form.needs-validation button[type="submit"]').click();
    await page.waitForURL('**/appointments-add.php?**updated=1');
    check(await page.getByText('Design QA Updated', { exact: true }).count() > 0, 'Appointment editing retains updated session data');
    const checkin = page.locator('form').filter({ has: page.locator('input[value="checkin"]') });
    await checkin.locator('button').click();
    await page.waitForURL('**/appointments-add.php?**checkedin=1');
    check(await page.getByText('Checked in', { exact: true }).count() > 0, 'Appointment check-in still updates status');
    await visit('appointments');
    await page.locator('#tableQuickSearch').fill("UI Review O'Connor");
    await page.waitForFunction(() => document.querySelector('#appointmentsTable-count').textContent.startsWith('1 of'));
    page.once('dialog', dialog => dialog.accept());
    await page.locator('tr:not([hidden]) [data-delete-name]').click();
    await page.waitForFunction(() => !document.querySelector('.filter-empty').hidden);
    check(await page.locator('.filter-empty').isVisible(), 'Preview deletion handles quoted names and refreshes filter counts');

    await visit('gate');
    await page.locator('#scanInput').fill('APT-26-0415');
    await page.locator('#scanBtn').click();
    check(await page.locator('#scanResult').getAttribute('class').then(c => c.includes('bad')), 'Pending gate pass still shows blocked feedback');
    await page.locator('#scanInput').fill('GP-26-08812');
    await page.locator('#scanInput').press('Enter');
    check(await page.getByRole('button', { name: 'Record exit' }).isVisible(), 'Valid gate lookup retains its action');

    await visit('organization');
    await page.getByRole('tab', { name: 'Profile', exact: true }).click();
    await page.locator('#oProfile button[type="submit"]').click();
    check(await page.locator('#appToast').isVisible(), 'Inline prototype forms show feedback without reloading');
    await visit('dashboard', 'list', '?role=security');
    check(await page.locator('.nav-item-link', { hasText: 'Organization' }).count() === 0, 'Role preview keeps unauthorized modules out of navigation');
    await page.keyboard.press('Control+k');
    await page.locator('#workspaceQuery').fill('organization');
    check(await page.locator('.workspace-result:not([hidden])').count() === 0, 'Workspace search respects role visibility');
    await page.keyboard.press('Escape');
    await visit('users');
    check(await page.getByRole('heading', { name: 'Access Restricted' }).isVisible(), 'Direct restricted routes retain their access guard');
    await visit('gate', 'list', '?role=auditor');
    const readonlyWrite = await context.request.post(moduleUrl('appointments', 'add'), { form: { form_action: 'update', ref: id, visitor: 'Denied update' }, maxRedirects: 0 });
    check(readonlyWrite.status() === 403, 'Auditor appointment submissions are rejected before a write');
    check(await page.locator('[data-delete-name]').count() === 0, 'Auditor list omits editing and deletion actions');
    await page.locator('#scanInput').fill('GP-26-08812');
    await page.locator('#scanBtn').click();
    check(await page.getByRole('button', { name: 'Record exit' }).count() === 0, 'Auditor gate lookup stays read only');
    await visit('dashboard', 'list', '?role=super_admin');

    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Toggle navigation' }).click();
    await page.locator('#sidebar.show').waitFor();
    await axe('Mobile navigation passes automated accessibility checks');
    await page.keyboard.press('Escape');
    await page.locator('#sidebar.show').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Search workspaces', exact: true }).last().click();
    await page.locator('#workspaceQuery').waitFor({ state: 'visible' });
    check(await page.locator('#workspaceQuery').isVisible(), 'Mobile header opens workspace search');
    await page.keyboard.press('Escape');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await visit('dashboard');
    check(await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length) === 0, 'Reduced motion disables CSS and chart animation');
    await visit('passes');
    await page.emulateMedia({ media: 'print', reducedMotion: 'reduce' });
    check(await page.locator('.main-wrapper').evaluate(el => getComputedStyle(el).marginLeft) === '0px', 'Print layout removes the sidebar offset');
    check(await page.locator('#badge').isVisible(), 'Gate badge remains visible for printing');
    await page.emulateMedia({ media: 'screen', reducedMotion: 'no-preference' });

    // A blocked storage API must not interrupt filtering or dialog initialization.
    const storageContext = await browser.newContext();
    await storageContext.addCookies(await context.cookies());
    await storageContext.addInitScript(() => { Storage.prototype.getItem = () => { throw new Error('Storage unavailable'); }; Storage.prototype.setItem = () => { throw new Error('Storage unavailable'); }; });
    const storagePage = await storageContext.newPage();
    storagePage.on('pageerror', e => errors.push(e.message));
    await storagePage.goto(moduleUrl('appointments'));
    check(await storagePage.locator('.table-feedback').count() === 1, 'Restricted sessionStorage does not break application initialization');
    await storageContext.close();

    const noJs = await browser.newContext({ javaScriptEnabled: false });
    await noJs.addCookies(await context.cookies());
    const fallback = await noJs.newPage();
    await fallback.goto(moduleUrl('dashboard'));
    check(await fallback.getByRole('heading', { name: 'Site overview' }).isVisible(), 'Main content remains visible without JavaScript');
    await noJs.close();
    await page.goto(base + 'logout.php');
    check(page.url().includes('login.php'), 'Logout returns to sign-in');
    check(errors.length === 0, 'No browser runtime errors across tested workflows');
    fs.mkdirSync('.tools/audit', { recursive: true });
    fs.writeFileSync('.tools/audit/workflows.json', JSON.stringify({ checks, errors }, null, 2));
    console.log(`${checks.length} workflow checks passed`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
